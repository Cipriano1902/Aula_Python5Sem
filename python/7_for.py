palavra = 'Josue'

for letra in palavra:
    if letra == 'J':
         print('jovem')
    if letra == 'o':
        print('otimista')
    if letra == 's':
         print('sincero')
    if letra == 'u':
         print('unico')
    if letra == 'e':
         print('energico')