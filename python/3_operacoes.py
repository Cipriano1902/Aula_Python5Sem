# Como realizar operações aritméticas em Python:

numero1 = 10
numero2 = 5

soma = numero1 + numero2
subtracao = numero1 - numero2
multiplicacao = numero1 * numero2
divisao = numero1 / numero2

print(soma)
print(subtracao)
print(multiplicacao)
print(divisao)  

resultado = numero1 + (numero1 * numero2) / numero1

print(resultado)

# Potência e Divisão inteira:

potencia = numero1 ** numero2
divisao_inteira = numero2 // numero1

print(potencia)
print(divisao_inteira)

